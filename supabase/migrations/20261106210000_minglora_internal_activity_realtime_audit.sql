-- Minglora internal operations activity journal, live publication and retention.
BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_cron;

CREATE TABLE IF NOT EXISTS public.minglora_internal_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  event_type text NOT NULL,
  source_table text NOT NULL,
  operation text NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
  record_id text,
  actor_id uuid,
  collections text[] NOT NULL DEFAULT '{}'::text[]
);

CREATE INDEX IF NOT EXISTS minglora_internal_activity_occurred_idx
  ON public.minglora_internal_activity (occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS minglora_internal_activity_source_idx
  ON public.minglora_internal_activity (source_table, id DESC);

ALTER TABLE public.minglora_internal_activity ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.minglora_internal_activity FROM PUBLIC, anon;
GRANT SELECT ON TABLE public.minglora_internal_activity TO authenticated, service_role;

DROP POLICY IF EXISTS minglora_owner_read_internal_activity
  ON public.minglora_internal_activity;
CREATE POLICY minglora_owner_read_internal_activity
  ON public.minglora_internal_activity
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = '5b998c21-86b5-4621-ab37-e0808a2657b1'::uuid);

CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.minglora_capture_internal_activity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, private
AS $function$
DECLARE
  row_data jsonb;
  record_key text;
  actor_text text;
  actor_uuid uuid;
  changed_collections text[] := ARRAY[]::text[];
  event_name text;
BEGIN
  IF TG_TABLE_NAME = 'minglora_runtime_state' THEN
    IF TG_OP = 'UPDATE' THEN
      SELECT coalesce(array_agg(keys.collection_key ORDER BY keys.collection_key), ARRAY[]::text[])
        INTO changed_collections
      FROM (
        SELECT key AS collection_key FROM jsonb_object_keys(OLD.state) AS old_keys(key)
        UNION
        SELECT key AS collection_key FROM jsonb_object_keys(NEW.state) AS new_keys(key)
      ) AS keys
      WHERE (OLD.state -> keys.collection_key) IS DISTINCT FROM (NEW.state -> keys.collection_key);

      IF coalesce(array_length(changed_collections, 1), 0) = 0 THEN
        RETURN NEW;
      END IF;
      record_key := NEW.revision::text;
      event_name := 'runtime_state_changed';
    ELSIF TG_OP = 'INSERT' THEN
      SELECT coalesce(array_agg(key ORDER BY key), ARRAY[]::text[])
        INTO changed_collections
      FROM jsonb_object_keys(NEW.state) AS state_keys(key);
      record_key := NEW.revision::text;
      event_name := 'runtime_state_initialized';
    ELSE
      SELECT coalesce(array_agg(key ORDER BY key), ARRAY[]::text[])
        INTO changed_collections
      FROM jsonb_object_keys(OLD.state) AS state_keys(key);
      record_key := OLD.revision::text;
      event_name := 'runtime_state_removed';
    END IF;
  ELSE
    IF TG_OP = 'DELETE' THEN
      row_data := to_jsonb(OLD);
    ELSE
      row_data := to_jsonb(NEW);
    END IF;

    record_key := coalesce(
      row_data ->> 'id',
      row_data ->> 'user_id',
      row_data ->> 'state_key',
      row_data ->> 'reference_id',
      row_data ->> 'request_id'
    );
    actor_text := coalesce(
      row_data ->> 'actor_id',
      row_data ->> 'user_id',
      row_data ->> 'author_id',
      row_data ->> 'sender_id',
      row_data ->> 'creator_id',
      row_data ->> 'host_id',
      row_data ->> 'owner_id',
      row_data ->> 'created_by',
      row_data ->> 'admin_user_id',
      row_data ->> 'reviewed_by',
      row_data ->> 'follower_id',
      row_data ->> 'updated_by'
    );
    IF actor_text ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
      actor_uuid := actor_text::uuid;
    END IF;
    changed_collections := ARRAY[TG_TABLE_NAME];
    event_name := TG_TABLE_NAME || '_' || lower(TG_OP);
  END IF;

  INSERT INTO public.minglora_internal_activity (
    event_type, source_table, operation, record_id, actor_id, collections
  ) VALUES (
    event_name, TG_TABLE_NAME, TG_OP, left(record_key, 160), actor_uuid, changed_collections
  );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION private.minglora_capture_internal_activity() FROM PUBLIC, anon, authenticated;

DO $triggers$
DECLARE
  target record;
BEGIN
  FOR target IN
    SELECT tablename
    FROM pg_tables
    WHERE schemaname = 'public'
      AND tablename NOT IN ('minglora_internal_activity', 'minglora_runtime_api_secrets')
  LOOP
    EXECUTE format(
      'DROP TRIGGER IF EXISTS trg_minglora_internal_activity ON public.%I',
      target.tablename
    );
    EXECUTE format(
      'CREATE TRIGGER trg_minglora_internal_activity
       AFTER INSERT OR UPDATE OR DELETE ON public.%I
       FOR EACH ROW EXECUTE FUNCTION private.minglora_capture_internal_activity()',
      target.tablename
    );
  END LOOP;
END;
$triggers$;

ALTER TABLE public.minglora_internal_activity REPLICA IDENTITY DEFAULT;
DO $publication$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
     AND NOT EXISTS (
       SELECT 1 FROM pg_publication_tables
       WHERE pubname = 'supabase_realtime'
         AND schemaname = 'public'
         AND tablename = 'minglora_internal_activity'
     ) THEN
    EXECUTE 'ALTER PUBLICATION supabase_realtime ADD TABLE public.minglora_internal_activity';
  END IF;
END;
$publication$;

DO $retention$
DECLARE
  existing_job record;
BEGIN
  IF to_regclass('cron.job') IS NOT NULL THEN
    FOR existing_job IN SELECT jobid FROM cron.job WHERE jobname = 'minglora_internal_activity_retention'
    LOOP
      PERFORM cron.unschedule(existing_job.jobid);
    END LOOP;
    PERFORM cron.schedule(
      'minglora_internal_activity_retention',
      '23 3 * * *',
      'DELETE FROM public.minglora_internal_activity WHERE occurred_at < now() - interval ''90 days'''
    );
  END IF;
END;
$retention$;

COMMIT;